// What the release review leaves out, and the check that verifies each thing instead.
//
// Why a list and not a size cut-off: in the 2026-11-15 release 62% of the 10.1 MB remerge diff was
// generated or mechanical (a 3.4 MB minified mermaid bundle, ratchet baselines, locale catalogs), and
// six Opus slices spent their reading on it. Leaving content out is only safe when something else
// verifies it, so every rule names that check, and a rule whose check cannot be found in this tree
// excludes nothing: the file stays in a slice and the packet says why.
//
// Each covering check is a name the gates already run:
//   gate-lint:<step>            a step `local/gate-lint.mjs` runs at the release gate
//   post-sync:<row>             a row `local/sync/post-sync.mjs` runs on the merged tip
//   mobile-postinstall:<script> a generator `mobile/package.json` postinstall re-runs on every install
import { existsSync, readFileSync } from 'node:fs'
import { basename, join } from 'node:path'
import { FORK_LINT_STEPS, resolveGateSteps } from '../gate-lint.mjs'
import { postSyncRowIds } from '../sync/lib/post-sync-rows.mjs'

const fixed =
  (...checks) =>
  () =>
    checks

export const EXCLUSIONS = [
  {
    id: 'renderer-locales',
    pattern: /^src\/renderer\/src\/i18n\/locales\/[^/]+\.json$/,
    covers: fixed('post-sync:locale-drift', 'gate-lint:verify:localization-catalogs'),
    why: 'upstream owns every catalog byte-for-byte (LOCAL-PATCHES.md § local(i18n)); the fork strings live in i18n/fork/',
    residual: null
  },
  {
    id: 'ratchet-baselines',
    pattern: /^config\/[^/]+-baseline\.txt$/,
    // Why per file: each baseline belongs to one ratchet, and a baseline whose ratchet the release
    // gate does not run (react-compiler-bailout runs only in upstream CI) has no check here.
    covers: (entry, context) => {
      const step = context.lintStepReading(basename(entry.path))
      return step ? [`gate-lint:${step}`] : null
    },
    why: 'a list of known offenders; its ratchet fails when the tree grows past it',
    residual:
      'an edit that raises an allowance still passes; the +/- counts show whether a list grew'
  },
  {
    id: 'rpc-params-catalog',
    pattern: /^src\/shared\/rpc-contract\/rpc-params-catalog\.generated\.ts$/,
    covers: fixed('gate-lint:verify:rpc-params-catalog'),
    why: 'generated from the RPC param schemas; the verifier regenerates and compares',
    residual: null
  },
  {
    id: 'acp-protocol',
    pattern: /^src\/main\/acp\/generated\/acp-protocol\.generated\.ts$/,
    covers: fixed('gate-lint:verify:acp-protocol'),
    why: 'generated from the pinned ACP schema; the header digests are checked',
    residual: null
  },
  {
    id: 'skill-bundle-manifest',
    pattern:
      /^(?:resources\/skills\/current-manifest\.json|src\/main\/skills\/bundled-skill-install\/bundled-skill-sources\.ts)$/,
    covers: fixed('gate-lint:verify:skill-bundle-manifest'),
    why: 'both are written by generate-skill-bundle-manifest.mjs from skills/**',
    residual: null
  },
  {
    id: 'bundled-skill-guides',
    pattern: /^src\/cli\/skills\/bundled-skill-guides\.ts$/,
    covers: fixed('gate-lint:verify:bundled-skill-guides'),
    why: 'written by generate-bundled-skill-guides.mjs from the skill markdown',
    residual: null
  },
  {
    id: 'mobile-vendor-bundles',
    pattern: /^mobile\/src\/.+\.generated\.ts$/,
    // Why the file's own header: the generator is the only thing that vouches for the content, and a
    // generated file whose header names no generator postinstall runs is not mechanical any more.
    covers: (entry, context) => {
      const generator = /^\+\/\/ Generated by (scripts\/[\w./-]+\.mjs)/m.exec(entry.text)?.[1]
      return generator && context.mobilePostinstall.includes(generator)
        ? [`mobile-postinstall:${generator}`]
        : null
    },
    why: 'minified vendor output (mermaid, xterm, katex) rebuilt by the mobile postinstall',
    residual:
      'whether the file belongs in git at all: the generators write gitignored paths, so a committed copy is worth a look'
  }
]

function scriptPathOf(step, scripts) {
  if (step.argv[0] === 'node') {
    return step.argv[1]
  }
  const command = step.argv[0] === 'pnpm' ? scripts[step.argv[2]] : null
  return /^(?:node|bun) ([\w./-]+\.mjs)\b/.exec(command ?? '')?.[1] ?? null
}

/** The checks this tree actually has, so a rule can only point at a check that runs. */
export function loadCoverageContext(root) {
  const scripts = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).scripts ?? {}
  const steps = resolveGateSteps(scripts, FORK_LINT_STEPS, root)
  const sources = new Map()
  for (const step of steps) {
    const file = scriptPathOf(step, scripts)
    if (file && existsSync(join(root, file))) {
      sources.set(step.id, readFileSync(join(root, file), 'utf8'))
    }
  }
  const mobileManifest = join(root, 'mobile', 'package.json')
  const mobileScripts = existsSync(mobileManifest)
    ? (JSON.parse(readFileSync(mobileManifest, 'utf8')).scripts ?? {})
    : {}
  return {
    lintSteps: new Set(steps.map((step) => step.id)),
    postSyncRows: new Set(postSyncRowIds()),
    mobilePostinstall: String(mobileScripts.postinstall ?? ''),
    lintStepReading: (name) => [...sources].find(([, text]) => text.includes(name))?.[0] ?? null
  }
}

/** Whether a named check exists in this tree. Unknown kinds are refused, not trusted. */
export function checkExists(check, context) {
  const [kind, ...rest] = check.split(':')
  const name = rest.join(':')
  if (kind === 'gate-lint') {
    return context.lintSteps.has(name)
  }
  if (kind === 'post-sync') {
    return context.postSyncRows.has(name)
  }
  if (kind === 'mobile-postinstall') {
    return Boolean(name) && context.mobilePostinstall.includes(name)
  }
  return false
}

/**
 * Splits the diff's files into the reviewed and the excluded. A file a rule matches but whose checks
 * are not all present is `uncovered`: it stays reviewed, and the packet records the miss.
 */
export function partitionEntries(entries, context, rules = EXCLUSIONS) {
  const reviewed = []
  const excluded = []
  const uncovered = []
  for (const entry of entries) {
    const rule = rules.find((candidate) => candidate.pattern.test(entry.path))
    if (!rule) {
      reviewed.push(entry)
      continue
    }
    const checks = rule.covers(entry, context)
    const missing = checks ? checks.filter((check) => !checkExists(check, context)) : null
    if (!checks || !checks.length || missing.length) {
      reviewed.push(entry)
      uncovered.push({
        path: entry.path,
        rule: rule.id,
        reason: checks ? `no such check: ${missing.join(', ')}` : 'no covering check found'
      })
      continue
    }
    excluded.push({ ...entry, rule: rule.id, covers: checks })
  }
  return { reviewed, excluded, uncovered }
}
