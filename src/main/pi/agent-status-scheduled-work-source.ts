import type { PiAgentKind } from '../../shared/agent-launch/catalog/pi-agent-kind'

/** Scheduled work is the Pi lane's monitoring input: a loop, a pending wakeup or a cold job will re-enter
 *  this session after its turn ends, so the pane must not read `done` while one is armed.
 *
 *  `/loop` presents one surface over two backends, so the inventory comes from two channels:
 *  - `loop:rpc:schedules:list` — live loops and self-paced wakeups, served by the user's `loop` extension.
 *  - `subagents:rpc:schedules:list` — cold jobs in pi-subagents' scheduler, keyed by session id.
 *
 *  Both homes can be paused (`manage_schedules` presents them as one roster), and both keep listing a
 *  paused job with its id and cadence while it arms nothing, so presence alone is not a claim: a paused
 *  or disabled job holds nothing. `loop:state` is `/loop`'s armed set — only jobs with an armed fire — so
 *  it announces an arm, pause or resume between turns; a dynamic loop between wakeups moves it silently.
 *
 *  Nothing here is inferred from tool calls: a `ScheduleWakeup` fallback covers dynamic loops only, and
 *  would miss fixed loops and cold jobs entirely. A channel nothing answers is absent, never empty — no
 *  inventory means no hold, which is what keeps an older build reading exactly as it does today.
 *
 *  The RPC never sits inside a post: the answer is cached here, and `piScheduledWorkField()` reads the
 *  cache while a post is being built, so the 1s delivery budget is untouched. */
export function getPiAgentStatusScheduledWorkModuleLines(kind: PiAgentKind): string[] {
  if (kind !== 'pi') {
    return []
  }

  return [
    'type PiScheduledWorkJob = { id: string; kind: "live" | "cold"; nextAt?: number }',
    'type PiScheduledWorkBus = {',
    '  on: (channel: string, listener: (payload: unknown) => void) => unknown',
    '  off?: (channel: string, listener: (payload: unknown) => void) => unknown',
    '  emit?: (channel: string, payload: unknown) => unknown',
    '}',
    'type PiScheduledWorkBinding = {',
    '  /** The bus this binding armed; Pi hands a re-run factory its own `pi.events`. */',
    '  bus: PiScheduledWorkBus',
    '  /** What `bus.on` handed back, when it hands anything back: the release this binding must call. */',
    '  listeners: { channel: string; listener: (payload: unknown) => void; release?: unknown }[]',
    '}',
    'type PiScheduledWorkState = {',
    '  /** The last answer from each channel, or null while that channel has none. */',
    '  live: PiScheduledWorkJob[] | null',
    '  cold: PiScheduledWorkJob[] | null',
    '  /** The bus the pane-owning registration was handed, so a timer can still ask after a reload. */',
    '  bus: PiScheduledWorkBus | null',
    '  /** The one binding this lane holds. Replaced, never accumulated, when the bus changes. */',
    '  binding: PiScheduledWorkBinding | null',
    '  /** Inventory last DELIVERED, so a refresh only speaks when the answer changed. */',
    '  postedKey: string',
    '  /** Inventory the post now being built carries; promoted to postedKey when it is delivered. */',
    '  builtKey: string',
    '  /** Epoch ms of the last built snapshot, so a silent held row is restated before it decays. */',
    '  postedAt: number',
    '  timer: ReturnType<typeof setTimeout> | null',
    '  updateTimer: ReturnType<typeof setTimeout> | null',
    '}',
    // Why globalThis: /reload re-evaluates this module and Pi hands the next factory a fresh bus, so a
    // module-scope cache would be rebuilt empty on every reload and lose the session its own loops.
    'declare global { var __orcaPiScheduledWork: PiScheduledWorkState | undefined }',
    'const piScheduledWork: PiScheduledWorkState = globalThis.__orcaPiScheduledWork ??= { live: null, cold: null, bus: null, binding: null, postedKey: "", builtKey: "", postedAt: 0, timer: null, updateTimer: null }',
    'let piScheduledWorkRequestId = 0',
    '// Why one outstanding ask per channel: a repeat replaces it instead of stacking listeners on a channel',
    '// that never answers. The age is what separates a slow reply from a channel nobody serves.',
    'const piScheduledWorkPending: { live: { release: () => void; at: number } | null; cold: { release: () => void; at: number } | null } = { live: null, cold: null }',
    'const PI_SCHEDULED_WORK_LIVE_CHANNEL = "loop:rpc:schedules:list"',
    'const PI_SCHEDULED_WORK_COLD_CHANNEL = "subagents:rpc:schedules:list"',
    '// Why a poll at all: `loop:state` announces what /loop changes, but an extension that stops answering,',
    '// or a claim nothing has cleared, is only visible by asking again. This bounds how stale a hold gets.',
    'const PI_SCHEDULED_WORK_POLL_MS = 60000',
    // Why discovery as well: every announcement this lane binds belongs to an extension that publishes, and
    // an older `/loop` answers `loop:rpc:schedules:list` while emitting nothing — so a loop armed in an idle
    // pane stays invisible until an unrelated post carries the field. Asking on a slow cadence is what finds
    // it; the poll above bounds a hold the pane already claims, and this bounds one it does not know about.
    'const PI_SCHEDULED_WORK_DISCOVERY_MS = 300000',
    'const PI_SCHEDULED_WORK_MIN_RECHECK_MS = 5000',
    'const PI_SCHEDULED_WORK_GRACE_MS = 30000',
    // Why: a silent monitoring row decays to unverifiable at 30 minutes; restating keeps it evidence-backed.',
    'const PI_SCHEDULED_WORK_HEARTBEAT_MS = 600000',
    '// Why retry rather than drop: a post already in flight carries the inventory as it was when its body',
    '// was built, so a change that landed after that would otherwise never be published.',
    'const PI_SCHEDULED_WORK_UPDATE_RETRY_MS = 500',
    'const PI_SCHEDULED_WORK_MAX_JOBS = 20',
    "// Why only the published channels: /loop's own create/remove requests are request channels this lane",
    '// binds before the loop extension does, so asking on them reads the inventory before the change lands.',
    '// `loop:state` is the armed set `/loop` publishes itself, whenever that set changes, so a loop armed,',
    '// paused or re-armed between turns is seen without waiting for one. A loop with no armed fire — a dynamic',
    '// loop between wakeups — is outside that set, so ending one moves nothing and only over-holds.',
    'const PI_SCHEDULED_WORK_EVENT_CHANNELS = ["subagents:scheduled", "subagents:scheduler_ready", "loop:state"]',
    '',
    'function piScheduledWorkJobs(): PiScheduledWorkJob[] {',
    '  const jobs: PiScheduledWorkJob[] = []',
    '  for (const job of piScheduledWork.live ?? []) jobs.push(job)',
    '  for (const job of piScheduledWork.cold ?? []) jobs.push(job)',
    '  return jobs',
    '}',
    '',
    'function piScheduledWorkRelease(kind: "live" | "cold"): void {',
    '  const pending = piScheduledWorkPending[kind]',
    '  if (!pending) return',
    '  piScheduledWorkPending[kind] = null',
    '  pending.release()',
    '}',
    '',
    '// Why no timeout timer: the extension must leave a turn end with nothing armed, and an in-process',
    '// responder answers inside the emit. A channel that stops answering is dropped on the next ask — the',
    '// previous ask is still pending, which is the only evidence that nothing is listening any more.',
    'function piScheduledWorkAsk(channel: string, kind: "live" | "cold"): void {',
    '  const bus = piScheduledWork.bus',
    "  if (!bus || typeof bus.on !== 'function' || typeof bus.emit !== 'function') return",
    '  const pending = piScheduledWorkPending[kind]',
    '  // Why the age: a reply that is merely slower than the next ask (pi-subagents awaits its handler) is',
    '  // not a dead channel, and dropping its slice would flash the row done between two ticks.',
    '  const unanswered = pending !== null && Date.now() - pending.at >= PI_SCHEDULED_WORK_MIN_RECHECK_MS',
    '  // Why carried forward: restamping on every ask would reset the age, so a channel asked again',
    '  // inside the window would never look dead.',
    '  const pendingSince = pending?.at',
    '  piScheduledWorkRelease(kind)',
    '  // Why clear on an unanswered ask: a channel that answered once and then stopped would otherwise pin',
    '  // the row working for the rest of the session on an inventory nothing is refreshing.',
    '  if (unanswered) piScheduledWork[kind] = null',
    '  const requestId = "orca-status-" + (++piScheduledWorkRequestId)',
    '  const replyChannel = channel + ":reply:" + requestId',
    '  let settled = false',
    '  const release = (): void => {',
    '    try {',
    '      if (typeof unsubscribe === "function") unsubscribe()',
    '      else bus.off?.(replyChannel, listener)',
    '    } catch {',
    '      // A bus without a release path leaves one listener; the next refresh replaces it.',
    '    }',
    '  }',
    '  const finish = (jobs: PiScheduledWorkJob[] | null): void => {',
    '    if (settled) return',
    '    settled = true',
    '    release()',
    '    piScheduledWorkPending[kind] = null',
    '    piScheduledWork[kind] = jobs',
    '    piScheduledWorkAfterRefresh()',
    '  }',
    '  const listener = (raw: unknown): void => {',
    '    const reply = raw as { success?: unknown; data?: unknown } | null | undefined',
    '    finish(reply?.success === true ? piScheduledWorkReadJobs(reply.data, kind) : null)',
    '  }',
    '  const unsubscribe = bus.on(replyChannel, listener) as (() => void) | null',
    '  piScheduledWorkPending[kind] = { release, at: pendingSince ?? Date.now() }',
    '  try {',
    '    bus.emit(channel, { requestId })',
    '  } catch {',
    '    finish(null)',
    '  }',
    '}',
    '',
    'function piScheduledWorkDisarm(): void {',
    '  if (piScheduledWork.timer !== null) clearTimeout(piScheduledWork.timer)',
    '  piScheduledWork.timer = null',
    '}',
    '',
    '// Why bounded by the poll: an inventory that never clears must not be believed forever, and the poll is',
    '// the only thing that can notice a loop stopped by a command that publishes nothing. It stays armed',
    '// while the pane still claims a hold, so an update lost to a failed delivery is still retried.',
    'function piScheduledWorkArm(): void {',
    '  piScheduledWorkDisarm()',
    '  const holding = piScheduledWorkJobs().length > 0 || piScheduledWork.postedKey !== "" || piScheduledWork.builtKey !== ""',
    '  const served = piScheduledWork.live !== null || piScheduledWork.cold !== null',
    '  // The horizon: the poll while the pane claims a hold, the discovery cadence while a home answers but',
    '  // nothing is armed, and none while no home has ever answered — so a build serving neither channel keeps',
    '  // the zero footprint it had, and a channel retired by an unanswered ask drops out of this.',
    '  const horizonMs = holding ? PI_SCHEDULED_WORK_POLL_MS : served ? PI_SCHEDULED_WORK_DISCOVERY_MS : 0',
    '  if (horizonMs === 0) return',
    '  const now = Date.now()',
    '  let soonest = now + horizonMs',
    '  for (const job of piScheduledWorkJobs()) {',
    "    if (typeof job.nextAt !== 'number') continue",
    '    soonest = Math.min(soonest, job.nextAt + PI_SCHEDULED_WORK_GRACE_MS)',
    '  }',
    '  // Why a floor: a fire that is already overdue would otherwise re-check on every tick, and a loop',
    '  // waiting for an idle session sits overdue for the whole turn.',
    '  const delay = Math.min(Math.max(soonest - now, PI_SCHEDULED_WORK_MIN_RECHECK_MS), horizonMs)',
    '  piScheduledWork.timer = setTimeout(() => {',
    '    piScheduledWork.timer = null',
    '    piScheduledWorkRefresh()',
    '  }, delay)',
    '  if (typeof piScheduledWork.timer.unref === "function") piScheduledWork.timer.unref()',
    '}',
    '',
    '// Why the key excludes the countdown: only a change in what is armed changes the hold, so a fire that',
    '// merely moves `nextAt` must not post.',
    'function piScheduledWorkKey(): string {',
    '  return piScheduledWorkJobs().map((job) => job.id + ":" + job.kind).join("|")',
    '}',
    '',
    'function piScheduledWorkFlushUpdate(): void {',
    '  piScheduledWork.updateTimer = null',
    '  if (isOmpRuntime()) return',
    '  // Why: a turn in flight will carry the field at its own end.',
    '  if (!postQueue.turnEnded) return',
    '  if (postQueue.activePost) {',
    '    piScheduledWork.updateTimer = setTimeout(piScheduledWorkFlushUpdate, PI_SCHEDULED_WORK_UPDATE_RETRY_MS)',
    '    if (typeof piScheduledWork.updateTimer.unref === "function") piScheduledWork.updateTimer.unref()',
    '    return',
    '  }',
    "  // Why: a completion that never reached Orca is still owed to the host, and this lane's restatement",
    "  // would take the endpoint watch's snapshot with it.",
    '  if (!postQueue.completionDelivered) return',
    '  // Why: a queued post builds its body later, so it already carries the newest inventory.',
    '  if (hasQueuedPost()) return',
    '  const key = piScheduledWorkKey()',
    '  const changed = key !== piScheduledWork.postedKey',
    '  // Why only while holding: a restatement exists to keep a held row fresh, so an empty inventory has',
    '  // nothing to say and no clock to reset.',
    '  const stale =',
    '    key !== "" && Date.now() - piScheduledWork.postedAt > PI_SCHEDULED_WORK_HEARTBEAT_MS',
    '  if (!changed && !stale) return',
    "  post('scheduled_work_update')",
    '}',
    '',
    'function piScheduledWorkScheduleUpdate(): void {',
    '  if (piScheduledWork.updateTimer !== null) return',
    '  piScheduledWork.updateTimer = setTimeout(piScheduledWorkFlushUpdate, 0)',
    '  if (typeof piScheduledWork.updateTimer.unref === "function") piScheduledWork.updateTimer.unref()',
    '}',
    '',
    'function piScheduledWorkAfterRefresh(): void {',
    '  piScheduledWorkArm()',
    '  piScheduledWorkScheduleUpdate()',
    '}',
    '',
    'function piScheduledWorkRefresh(): void {',
    '  if (isOmpRuntime()) return',
    '  piScheduledWorkAsk(PI_SCHEDULED_WORK_LIVE_CHANNEL, "live")',
    '  piScheduledWorkAsk(PI_SCHEDULED_WORK_COLD_CHANNEL, "cold")',
    '  // Why re-arm here as well as on a reply: a channel that stopped answering never replies, and the',
    '  // re-check is the only thing that would ever notice. Arm owns the horizon, so an idle turn end on a',
    '  // build that serves neither channel still leaves no timer behind.',
    '  piScheduledWorkArm()',
    '  piScheduledWorkScheduleUpdate()',
    '}',
    '',
    '// Read while a post is being built, never at enqueue: a coalesced or retried post then carries the',
    '// inventory that is true when it is actually sent.',
    'function piScheduledWorkField(): Record<string, unknown> {',
    '  if (isOmpRuntime()) return {}',
    '  const jobs = piScheduledWorkJobs()',
    '  if (jobs.length === 0) {',
    '    piScheduledWork.builtKey = ""',
    '    return {}',
    '  }',
    '  const now = Date.now()',
    '  const wire = jobs.slice(0, PI_SCHEDULED_WORK_MAX_JOBS).map((job) => ({',
    '    id: job.id,',
    '    kind: job.kind,',
    '    ...(typeof job.nextAt === "number" ? { next_in_ms: Math.round(job.nextAt - now) } : {}),',
    '  }))',
    '  piScheduledWork.postedAt = now',
    '  piScheduledWork.builtKey = piScheduledWorkKey()',
    '  return { scheduled_work: { jobs: wire } }',
    '}',
    '',
    '// Why on delivery and not on build: a build that never reached Orca must not be what tells the next',
    '// re-check there is nothing left to say.',
    'function piScheduledWorkDelivered(): void {',
    '  piScheduledWork.postedKey = piScheduledWork.builtKey',
    '}',
    '',
    'function piScheduledWorkReset(): void {',
    '  piScheduledWorkDisarm()',
    '  if (piScheduledWork.updateTimer !== null) clearTimeout(piScheduledWork.updateTimer)',
    '  piScheduledWork.updateTimer = null',
    '  piScheduledWork.live = null',
    '  piScheduledWork.cold = null',
    '  piScheduledWork.postedKey = ""',
    '  piScheduledWork.builtKey = ""',
    '  piScheduledWork.postedAt = 0',
    '  piScheduledWorkRelease("live")',
    '  piScheduledWorkRelease("cold")',
    '}',
    ''
  ]
}
