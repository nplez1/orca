import type { PiAgentKind } from '../../shared/pi-agent-kind'

/** Scheduled work is the Pi lane's monitoring input: a loop, a pending wakeup or a cold job will re-enter
 *  this session after its turn ends, so the pane must not read `done` while one is armed.
 *
 *  `/loop` presents one surface over two backends, so the inventory comes from two channels:
 *  - `loop:rpc:schedules:list` — live loops and self-paced wakeups, served by the user's `loop` extension.
 *  - `subagents:rpc:schedules:list` — cold jobs in pi-subagents' scheduler, keyed by session id.
 *
 *  Nothing here is inferred from tool calls: a `ScheduleWakeup` fallback covers dynamic loops only, and
 *  would miss fixed loops and cold jobs entirely. A channel nothing answers is absent, never empty — no
 *  inventory means no hold, which is what keeps an older build reading exactly as it does today.
 *
 *  The RPC never sits inside a post: the answer is cached here, and `piScheduledWorkField()` reads the
 *  cache while a post is being built, so the 1s delivery budget is untouched. */
export function getPiAgentStatusScheduledWorkModuleLines(kind: PiAgentKind): string[] {
  if (kind !== 'pi') {
    return []
  }

  return [
    'type PiScheduledWorkJob = { id: string; kind: "live" | "cold"; nextAt?: number }',
    'type PiScheduledWorkBus = {',
    '  on: (channel: string, listener: (payload: unknown) => void) => unknown',
    '  off?: (channel: string, listener: (payload: unknown) => void) => unknown',
    '  emit?: (channel: string, payload: unknown) => unknown',
    '}',
    'type PiScheduledWorkBinding = {',
    '  /** The bus this binding armed; Pi hands a re-run factory its own `pi.events`. */',
    '  bus: PiScheduledWorkBus',
    '  listeners: { channel: string; listener: (payload: unknown) => void }[]',
    '}',
    'type PiScheduledWorkState = {',
    '  /** The last answer from each channel, or null while that channel has none. */',
    '  live: PiScheduledWorkJob[] | null',
    '  cold: PiScheduledWorkJob[] | null',
    '  /** The bus the current registration was handed, so a timer can still ask after a reload. */',
    '  bus: PiScheduledWorkBus | null',
    '  /** Inventory last posted, so a refresh only speaks when the answer changed. */',
    '  postedKey: string',
    '  /** Epoch ms of the last snapshot, so a silent held row is restated before it decays. */',
    '  postedAt: number',
    '  timer: ReturnType<typeof setTimeout> | null',
    '  updateTimer: ReturnType<typeof setTimeout> | null',
    '}',
    // Why globalThis: /reload re-evaluates this module and Pi hands the next factory a fresh bus, so a
    // module-scope cache would be rebuilt empty on every reload and lose the session its own loops.
    'declare global { var __orcaPiScheduledWork: PiScheduledWorkState | undefined }',
    'const piScheduledWork: PiScheduledWorkState = globalThis.__orcaPiScheduledWork ??= { live: null, cold: null, bus: null, postedKey: "", postedAt: 0, timer: null, updateTimer: null }',
    'let piScheduledWorkBindings: PiScheduledWorkBinding[] = []',
    'let piScheduledWorkRequestId = 0',
    '// Why one outstanding ask per channel: a repeat replaces it instead of stacking listeners on a channel',
    '// that never answers.',
    'const piScheduledWorkPending: { live: (() => void) | null; cold: (() => void) | null } = { live: null, cold: null }',
    'const PI_SCHEDULED_WORK_LIVE_CHANNEL = "loop:rpc:schedules:list"',
    'const PI_SCHEDULED_WORK_COLD_CHANNEL = "subagents:rpc:schedules:list"',
    // Why a poll at all: a live loop armed, stopped or expired emits nothing on the bus, so the only way
    // to stop claiming a hold that no longer exists is to ask again. 60s bounds how long that can read stale.
    'const PI_SCHEDULED_WORK_POLL_MS = 60000',
    'const PI_SCHEDULED_WORK_GRACE_MS = 30000',
    // Why: a silent monitoring row decays to unverifiable at 30 minutes; restating keeps it evidence-backed.
    'const PI_SCHEDULED_WORK_HEARTBEAT_MS = 600000',
    'const PI_SCHEDULED_WORK_MAX_JOBS = 20',
    '// Why: cold-job and scheduler changes are published; live-loop changes are not.',
    'const PI_SCHEDULED_WORK_EVENT_CHANNELS = ["subagents:scheduled", "subagents:scheduler_ready", "loop:rpc:schedules:create", "loop:rpc:schedules:remove"]',
    '',
    'function piScheduledWorkJobs(): PiScheduledWorkJob[] {',
    '  const jobs: PiScheduledWorkJob[] = []',
    '  for (const job of piScheduledWork.live ?? []) jobs.push(job)',
    '  for (const job of piScheduledWork.cold ?? []) jobs.push(job)',
    '  return jobs',
    '}',
    '',
    '// Why structural and total: a newer scheduler adding a field must not break the footer, and a paused',
    '// job will not fire, so it holds nothing.',
    'function piScheduledWorkReadJobs(raw: unknown, kind: "live" | "cold"): PiScheduledWorkJob[] {',
    '  const jobs: PiScheduledWorkJob[] = []',
    '  const list = (raw as { jobs?: unknown } | null | undefined)?.jobs',
    '  if (!Array.isArray(list)) return jobs',
    '  for (const entry of list.slice(0, PI_SCHEDULED_WORK_MAX_JOBS)) {',
    "    if (!entry || typeof entry !== 'object') continue",
    '    const job = entry as { id?: unknown; enabled?: unknown; nextAt?: unknown; nextRun?: unknown }',
    "    if (typeof job.id !== 'string' || !job.id) continue",
    '    if (kind === "cold" && job.enabled === false) continue',
    '    const nextAt =',
    "      typeof job.nextAt === 'number' && Number.isFinite(job.nextAt)",
    '        ? job.nextAt',
    "        : typeof job.nextRun === 'string'",
    '          ? Date.parse(job.nextRun)',
    '          : Number.NaN',
    '    jobs.push({ id: job.id, kind, ...(Number.isFinite(nextAt) ? { nextAt } : {}) })',
    '  }',
    '  return jobs',
    '}',
    '',
    '// Why one-shot listeners: the reply channel is scoped to the request id, so two in-flight asks cannot',
    "// read each other's answers, and a channel that never answers leaves the slice absent rather than empty.",
    '// Why no timeout timer: the extension must leave a turn end with nothing armed, and an in-process',
    '// responder answers inside the emit. A channel nothing serves simply keeps its one pending listener,',
    '// which the next refresh replaces — bounded, and it cannot hold the process open.',
    'function piScheduledWorkAsk(channel: string, kind: "live" | "cold"): void {',
    '  const bus = piScheduledWork.bus',
    "  if (!bus || typeof bus.on !== 'function' || typeof bus.emit !== 'function') return",
    '  piScheduledWorkRelease(kind)',
    '  const requestId = "orca-status-" + (++piScheduledWorkRequestId)',
    '  const replyChannel = channel + ":reply:" + requestId',
    '  let settled = false',
    '  const release = (): void => {',
    '    try {',
    '      if (typeof unsubscribe === "function") unsubscribe()',
    '      else bus.off?.(replyChannel, listener)',
    '    } catch {',
    '      // A bus without a release path leaves one listener; the next refresh replaces it.',
    '    }',
    '  }',
    '  const finish = (jobs: PiScheduledWorkJob[] | null): void => {',
    '    if (settled) return',
    '    settled = true',
    '    release()',
    '    piScheduledWorkPending[kind] = null',
    '    piScheduledWork[kind] = jobs',
    '    piScheduledWorkAfterRefresh()',
    '  }',
    '  const listener = (raw: unknown): void => {',
    '    const reply = raw as { success?: unknown; data?: unknown } | null | undefined',
    '    finish(reply?.success === true ? piScheduledWorkReadJobs(reply.data, kind) : null)',
    '  }',
    '  const unsubscribe = bus.on(replyChannel, listener) as (() => void) | null',
    '  piScheduledWorkPending[kind] = release',
    '  try {',
    '    bus.emit(channel, { requestId })',
    '  } catch {',
    '    finish(null)',
    '  }',
    '}',
    '',
    'function piScheduledWorkRelease(kind: "live" | "cold"): void {',
    '  const pending = piScheduledWorkPending[kind]',
    '  if (!pending) return',
    '  piScheduledWorkPending[kind] = null',
    '  pending()',
    '}',
    '',
    'function piScheduledWorkDisarm(): void {',
    '  if (piScheduledWork.timer !== null) clearTimeout(piScheduledWork.timer)',
    '  piScheduledWork.timer = null',
    '}',
    '',
    '// Why bounded by the poll: an inventory that never clears must not be believed forever, and the poll is',
    '// the only thing that can notice a loop stopped by a command that publishes nothing.',
    'function piScheduledWorkArm(): void {',
    '  piScheduledWorkDisarm()',
    '  const jobs = piScheduledWorkJobs()',
    '  if (jobs.length === 0) return',
    '  const now = Date.now()',
    '  let soonest = now + PI_SCHEDULED_WORK_POLL_MS',
    '  for (const job of jobs) {',
    "    if (typeof job.nextAt !== 'number') continue",
    '    soonest = Math.min(soonest, job.nextAt + PI_SCHEDULED_WORK_GRACE_MS)',
    '  }',
    '  const delay = Math.max(1000, Math.min(soonest - now, PI_SCHEDULED_WORK_POLL_MS))',
    '  piScheduledWork.timer = setTimeout(() => {',
    '    piScheduledWork.timer = null',
    '    piScheduledWorkRefresh()',
    '  }, delay)',
    '  if (typeof piScheduledWork.timer.unref === "function") piScheduledWork.timer.unref()',
    '}',
    '',
    '// Why the key excludes the countdown: only a change in what is armed changes the hold, so a fire that',
    '// merely moves `nextAt` must not post.',
    'function piScheduledWorkKey(): string {',
    '  return piScheduledWorkJobs().map((job) => job.id + ":" + job.kind).join("|")',
    '}',
    '',
    'function piScheduledWorkFlushUpdate(): void {',
    '  piScheduledWork.updateTimer = null',
    '  if (isOmpRuntime()) return',
    '  // Why: a turn in flight will carry the field at its own end, and a post already queued carries it.',
    '  if (!postQueue.turnEnded || hasQueuedPost() || postQueue.activePost) return',
    '  const key = piScheduledWorkKey()',
    '  const changed = key !== piScheduledWork.postedKey',
    '  // Why only while holding: a restatement exists to keep a held row fresh, so an empty inventory has',
    '  // nothing to say and no clock to reset.',
    '  const stale =',
    '    key !== "" && Date.now() - piScheduledWork.postedAt > PI_SCHEDULED_WORK_HEARTBEAT_MS',
    '  if (!changed && !stale) return',
    "  post('scheduled_work_update')",
    '}',
    '',
    'function piScheduledWorkScheduleUpdate(): void {',
    '  if (piScheduledWork.updateTimer !== null) return',
    '  piScheduledWork.updateTimer = setTimeout(piScheduledWorkFlushUpdate, 0)',
    '  if (typeof piScheduledWork.updateTimer.unref === "function") piScheduledWork.updateTimer.unref()',
    '}',
    '',
    'function piScheduledWorkAfterRefresh(): void {',
    '  piScheduledWorkArm()',
    '  piScheduledWorkScheduleUpdate()',
    '}',
    '',
    'function piScheduledWorkRefresh(): void {',
    '  if (isOmpRuntime()) return',
    '  piScheduledWorkAsk(PI_SCHEDULED_WORK_LIVE_CHANNEL, "live")',
    '  piScheduledWorkAsk(PI_SCHEDULED_WORK_COLD_CHANNEL, "cold")',
    '}',
    '',
    '// Read while a post is being built, never at enqueue: a coalesced or retried post then carries the',
    '// inventory that is true when it is actually sent.',
    'function piScheduledWorkField(): Record<string, unknown> {',
    '  if (isOmpRuntime()) return {}',
    '  const jobs = piScheduledWorkJobs()',
    '  if (jobs.length === 0) {',
    '    piScheduledWork.postedKey = ""',
    '    return {}',
    '  }',
    '  const now = Date.now()',
    '  const wire = jobs.slice(0, PI_SCHEDULED_WORK_MAX_JOBS).map((job) => ({',
    '    id: job.id,',
    '    kind: job.kind,',
    '    ...(typeof job.nextAt === "number" ? { next_in_ms: Math.round(job.nextAt - now) } : {}),',
    '  }))',
    '  piScheduledWork.postedAt = now',
    '  piScheduledWork.postedKey = piScheduledWorkKey()',
    '  return { scheduled_work: { jobs: wire } }',
    '}',
    '',
    'function piScheduledWorkReset(): void {',
    '  piScheduledWorkDisarm()',
    '  if (piScheduledWork.updateTimer !== null) clearTimeout(piScheduledWork.updateTimer)',
    '  piScheduledWork.updateTimer = null',
    '  piScheduledWork.live = null',
    '  piScheduledWork.cold = null',
    '  piScheduledWork.postedKey = ""',
    '  piScheduledWork.postedAt = 0',
    '  piScheduledWorkRelease("live")',
    '  piScheduledWorkRelease("cold")',
    '}',
    ''
  ]
}

/** Bind the bus this registration was handed, once per bus object, and cache the current inventory.
 *
 *  Keyed by bus for the same reason the async-child lane is: Pi hands a re-run factory its own
 *  `pi.events` while `/reload` keeps the module, so a channel this lane has not armed is armed, and a bus
 *  already carrying this lane is never armed twice. */
export function getPiAgentStatusScheduledWorkSetupLines(kind: PiAgentKind): string[] {
  if (kind !== 'pi') {
    return []
  }

  return [
    '  piScheduledWork.bus = (pi as { events?: PiScheduledWorkBus } | null)?.events ?? null',
    '  if (piScheduledWork.bus && !piScheduledWorkBindings.some((binding) => binding.bus === piScheduledWork.bus)) {',
    '    try {',
    '      const binding: PiScheduledWorkBinding = { bus: piScheduledWork.bus, listeners: [] }',
    '      piScheduledWorkBindings.push(binding)',
    '      const onScheduledChange = (): void => { piScheduledWorkRefresh() }',
    '      for (const channel of PI_SCHEDULED_WORK_EVENT_CHANNELS) {',
    '        piScheduledWork.bus.on(channel, onScheduledChange)',
    '        binding.listeners.push({ channel, listener: onScheduledChange })',
    '      }',
    '    } catch {',
    '      // Why: status reporting must never fail the pi run; an unavailable bus just means no inventory.',
    '    }',
    '  }',
    '  piScheduledWorkRefresh()',
    ''
  ]
}
