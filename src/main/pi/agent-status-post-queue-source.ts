import type { PiAgentKind } from '../../shared/pi-agent-kind'

export function getPiAgentStatusPostQueueSourceLines(kind: PiAgentKind): string[] {
  return [
    'type HookSnapshot = { hookEventName: string; extra: Record<string, unknown>; metadata: Record<string, unknown>; ompRuntime: boolean }',
    'type HookPost = HookSnapshot & { revision: number; attempts: number; delivered: boolean; final?: boolean }',
    'type HookPostQueue = { activePost: HookPost | null; pendingPost: HookPost | null; latestPost: HookPost | null; finalPosts: HookPost[]; finalRetryTimer: ReturnType<typeof setTimeout> | null; postRevision: number; retryTimer: ReturnType<typeof setTimeout> | null; watchTimer: ReturnType<typeof setTimeout> | null; watchAttemptedKey: string | null; watchSnapshot: HookSnapshot | null; turnEnded: boolean; newestEnqueued: number; completionDelivered: boolean; completionWatchDeadline: number }',
    ...(kind === 'pi'
      ? [
          'declare global { var __orcaPiStatusPostQueue: HookPostQueue | undefined }',
          // Why: old delivery continuations and a reloaded registration must serialize through one queue.
          'const postQueue: HookPostQueue = globalThis.__orcaPiStatusPostQueue ??= { activePost: null, pendingPost: null, latestPost: null, finalPosts: [], finalRetryTimer: null, postRevision: 0, retryTimer: null, watchTimer: null, watchAttemptedKey: null, watchSnapshot: null, turnEnded: true, newestEnqueued: 0, completionDelivered: true, completionWatchDeadline: 0 }'
        ]
      : [
          'const postQueue: HookPostQueue = { activePost: null, pendingPost: null, latestPost: null, finalPosts: [], finalRetryTimer: null, postRevision: 0, retryTimer: null, watchTimer: null, watchAttemptedKey: null, watchSnapshot: null, turnEnded: true, newestEnqueued: 0, completionDelivered: true, completionWatchDeadline: 0 }'
        ]),
    '',
    'function cancelPostRetry(): void {',
    '  if (postQueue.retryTimer !== null) clearTimeout(postQueue.retryTimer)',
    '  postQueue.retryTimer = null',
    '}',
    '',
    '// Queued posts build their body later and already include newer state.',
    'function hasQueuedPost(): boolean {',
    '  return postQueue.pendingPost !== null || postQueue.retryTimer !== null',
    '}',
    '',
    'function resetPostQueue(): void {',
    '  cancelPostRetry()',
    '  // Why: the slot it is about to clear is the only evidence that something newer than the posts',
    '  // it promotes had been enqueued.',
    '  if (postQueue.latestPost) postQueue.newestEnqueued = postQueue.latestPost.revision',
    '  postQueue.postRevision++',
    // Keep object identity so in-flight acknowledgements retire the matching final entry.
    '  for (const post of [postQueue.activePost, postQueue.pendingPost, postQueue.latestPost]) {',
    "    if (!post || post.hookEventName !== 'agent_end' || post.delivered || post.final) continue",
    '    post.final = true',
    '    // Why the spent budget is kept: the retries a completion already used are retries of the same',
    '    // post, so promotion cannot hand out a fresh three on top of them.',
    '    postQueue.finalPosts.push(post)',
    '  }',
    '  postQueue.pendingPost = null',
    '  postQueue.latestPost = null',
    '  drainPosts()',
    '}',
    '',
    'function retireTurnCompletionPosts(metadata: Record<string, unknown>): void {',
    '  const first = postQueue.finalPosts[0]',
    '  for (const post of postQueue.finalPosts) {',
    '    if (post.extra.session_boundary !== true && post.metadata.session_id === metadata.session_id) post.final = false',
    '  }',
    '  postQueue.finalPosts = postQueue.finalPosts.filter((post) => post.final)',
    '  if (first && !first.final && postQueue.finalRetryTimer !== null) {',
    '    clearTimeout(postQueue.finalRetryTimer)',
    '    postQueue.finalRetryTimer = null',
    '  }',
    '}',
    '',
    // Why: Orca mints a new hook token on every start, so the endpoint a pane last attempted is how
    // a running agent notices the Orca it reports to was restarted. That Orca restored this pane\'s last
    // row from disk and cannot observe the agent again until it posts, and a turn can stay silent for a
    // long tool call or a subagent. So while work is in flight the agent speaks first and republishes the
    // state Orca already had, at the endpoint Orca is serving now.
    'const ENDPOINT_WATCH_MS = 2000',
    // Why bounded: the watch exists to re-announce a completion Orca never acknowledged, and a pane
    // whose Orca is gone must not poll for it for the rest of the run.
    'const COMPLETION_WATCH_MAX_MS = 60000',
    '',
    'function endpointKeyOf(coords: { port?: string; token?: string; env?: string; version?: string }): string {',
    "  return [coords.port, coords.token, coords.env, coords.version].join('|')",
    '}',
    '',
    "// Why: work in flight is the only window a restart can silently invalidate. An idle pane's row is",
    '// already `done`, so keeping a timer armed there would watch for nothing.',
    '// Why the endpoint-file gate: only a pane that can re-read its hook coordinates from disk can',
    '// ever notice a restart, so a pane launched without that file arms nothing at all.',
    'function startEndpointWatch(): void {',
    '  if (postQueue.watchTimer !== null || !process.env.ORCA_AGENT_HOOK_ENDPOINT) return',
    '  postQueue.watchTimer = setTimeout(watchEndpoint, ENDPOINT_WATCH_MS)',
    "  if (typeof postQueue.watchTimer.unref === 'function') postQueue.watchTimer.unref()",
    '}',
    '',
    'function stopEndpointWatch(): void {',
    '  if (postQueue.watchTimer !== null) clearTimeout(postQueue.watchTimer)',
    '  postQueue.watchTimer = null',
    '}',
    '',
    '// Why: a session that ends has nothing left to re-announce, and the next attempt arms again.',
    'function resetEndpointWatch(): void {',
    '  stopEndpointWatch()',
    '  postQueue.watchAttemptedKey = null',
    '  postQueue.watchSnapshot = null',
    '  postQueue.turnEnded = true',
    '}',
    '',
    "// Why: whether the pane is working is the pane's own report, and a child agent's registration in",
    '// this same process never reports one — so the watch reads the last attempt, never whichever',
    '// registration happens to be current. `extra.subagent_runs` is the fork lane, which posts the',
    "// lead's completion while its children still run; every other lane withholds that completion.",
    'function watchHeldByWork(): boolean {',
    '  const snapshot = postQueue.watchSnapshot',
    '  if (!snapshot) return false',
    '  const runs = snapshot.extra.subagent_runs',
    '  const childWork = Array.isArray(runs) && runs.length > 0',
    '  // Why the snapshot outranks the flag here: a reset can drop a turn start that was enqueued and',
    '  // never attempted, leaving a completion in hand with the flag already cleared — reporting that',
    '  // completion would tell a restarted Orca a working pane had finished.',
    "  if (snapshot.hookEventName === 'agent_end') {",
    '    // Why: a completion that never reached Orca leaves the pane reading "working" until the next',
    '    // prompt, so the watch stays armed to republish it — at the new endpoint if Orca restarted.',
    '    return childWork || (!postQueue.completionDelivered && Date.now() <= postQueue.completionWatchDeadline)',
    '  }',
    '  return !postQueue.turnEnded || childWork',
    '}',
    '',
    '// Why: "newest" is about what has been ENQUEUED since, not about the counter — a queue reset',
    '// bumps the counter itself, so a completion it promoted must not read as superseded.',
    'function isNewestEnqueue(next) {',
    '  if (next.revision === postQueue.postRevision) return true',
    '  // Why: a reset promotes a completion it never delivered, and that is the newest post only when',
    '  // nothing newer had been enqueued before the reset — otherwise a retry of it would re-end a',
    '  // turn that has already started.',
    '  return (',
    '    next.final === true &&',
    '    postQueue.latestPost === null &&',
    '    next.revision >= postQueue.newestEnqueued',
    '  )',
    '}',
    '',
    'function noteEndpointWatchAttempt(hookEventName, extra, metadata, ompRuntime, endpointKey, latest) {',
    '  postQueue.watchAttemptedKey = endpointKey',
    '  // Why only the latest enqueue speaks: a final retried while a newer turn is already queued',
    '  // describes the turn before it, and would otherwise re-end a turn that has since started.',
    '  if (latest) {',
    '    // Why again, on the delivered name: an OMP model switch that replaces an undelivered',
    '    // completion is attempted as agent_end, and the enqueue-time name was model_select.',
    "    if (hookEventName === 'agent_end') postQueue.turnEnded = true",
    "    else if (hookEventName === 'agent_start' || hookEventName === 'before_agent_start') postQueue.turnEnded = false",
    '    // Why: only a closing session retires the state Orca should be told about; a completion',
    '    // promoted to final by a queue reset is a reload or a sibling registration, not the end.',
    '    postQueue.watchSnapshot =',
    '      extra.session_boundary === true ? null : { hookEventName, extra, metadata, ompRuntime }',
    "    if (hookEventName === 'agent_end') {",
    '      postQueue.completionDelivered = false',
    '      postQueue.completionWatchDeadline = Date.now() + COMPLETION_WATCH_MAX_MS',
    '    }',
    '  }',
    '  if (watchHeldByWork()) startEndpointWatch()',
    '  else stopEndpointWatch()',
    '}',
    '',
    'function republishWatchSnapshot(): void {',
    '  const snapshot = postQueue.watchSnapshot',
    '  // Why: a queued post is newer than this snapshot, and a pending final must not be displaced.',
    '  if (!snapshot || postQueue.activePost || postQueue.pendingPost || postQueue.finalPosts.length > 0) return',
    '  // Why: a prompt already counted on the old Orca must not count as a new submission, and the turn',
    '  // it started is still the turn in flight.',
    "  const republished = snapshot.hookEventName === 'before_agent_start'",
    "    ? { ...snapshot, hookEventName: 'agent_start', extra: { ...snapshot.extra, prompt: undefined } }",
    '    : snapshot',
    '  postQueue.pendingPost = { ...republished, revision: ++postQueue.postRevision, attempts: 0, delivered: false }',
    '  postQueue.latestPost = postQueue.pendingPost',
    '  drainPosts()',
    '}',
    '',
    'function watchEndpoint(): void {',
    '  postQueue.watchTimer = null',
    '  try {',
    '    const key = endpointKeyOf(resolveHookCoords())',
    '    // Why: the key compared is the one last ATTEMPTED, so a restart is a key change while a',
    '    // repeated failure at one endpoint (the WSL curl bridge, a disabled-hook 404) cannot spin.',
    '    if (postQueue.watchAttemptedKey !== key) republishWatchSnapshot()',
    '  } catch {',
    '    // Why: status reporting must never break the pi run, including from a timer callback.',
    '  }',
    '  // Why: re-ask every tick, so a missed stop cannot leave an idle pane polling for good.',
    '  if (watchHeldByWork()) startEndpointWatch()',
    '}',
    '',
    'function drainPosts(): void {',
    // Old-session final retries must finish before new posts can become the last host status.
    '  if (postQueue.activePost || postQueue.finalRetryTimer !== null) return',
    '  const next = postQueue.finalPosts[0] ?? postQueue.pendingPost',
    '  if (!next) return',
    '  if (!next.final) postQueue.pendingPost = null',
    '  postQueue.activePost = next',
    '  void postOnce(next.hookEventName, next.extra, next.metadata, next.ompRuntime, next.final === true, isNewestEnqueue(next))',
    '    .then(() => {',
    '      next.delivered = true',
    "      if (next.hookEventName === 'agent_end') {",
    '        postQueue.completionDelivered = true',
    '        // Why the guard: children still running keep the roster snapshot the watch republishes.',
    '        if (!watchHeldByWork()) {',
    '          postQueue.watchSnapshot = null',
    '          stopEndpointWatch()',
    '        }',
    '      }',
    '      if (next.final) postQueue.finalPosts.shift()',
    '    })',
    '    .catch(() => {',
    '      if (next.final) {',
    '        if (next.attempts >= 3) {',
    '          postQueue.finalPosts.shift()',
    "          console.warn('[orca-pi-status] hook delivery failed after retries:', next.hookEventName)",
    '          return',
    '        }',
    '        postQueue.finalRetryTimer = setTimeout(() => {',
    '          postQueue.finalRetryTimer = null',
    '          drainPosts()',
    '        }, 250 * 2 ** next.attempts++)',
    "        if (typeof postQueue.finalRetryTimer.unref === 'function') postQueue.finalRetryTimer.unref()",
    '        return',
    '      }',
    '      // Why a completion retries too: a plain-pi failure was dropped outright, and the pane stayed',
    '      // working until the user typed again.',
    "      if (!(next.ompRuntime || next.hookEventName === 'agent_end') || next.revision !== postQueue.postRevision) return",
    '      if (next.attempts >= 3) {',
    "        console.warn('[orca-pi-status] hook delivery failed after retries:', next.hookEventName)",
    '        return',
    '      }',
    '      const delay = 250 * 2 ** next.attempts++',
    '      postQueue.retryTimer = setTimeout(() => {',
    '        postQueue.retryTimer = null',
    '        if (next.revision !== postQueue.postRevision) return',
    '        postQueue.pendingPost = next',
    '        drainPosts()',
    '      }, delay)',
    "      if (typeof postQueue.retryTimer.unref === 'function') postQueue.retryTimer.unref()",
    '    })',
    '    .finally(() => {',
    '      postQueue.activePost = null',
    '      drainPosts()',
    '    })',
    '}',
    ''
  ]
}
