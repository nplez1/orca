export function getPiAgentStatusWslCurlSourceLines(): string[] {
  return [
    '// WSL identity and host curl availability are process-constant; avoid repeated filesystem probes on failed delivery.',
    'let cachedIsWslRuntime: boolean | null = null',
    'let cachedWindowsCurlPath: string | null | undefined',
    '',
    'function isWslRuntime(): boolean {',
    '  if (cachedIsWslRuntime !== null) return cachedIsWslRuntime',
    '  cachedIsWslRuntime = detectWslRuntime()',
    '  return cachedIsWslRuntime',
    '}',
    '',
    'function detectWslRuntime(): boolean {',
    '  if (process.env.WSL_DISTRO_NAME) return true',
    '  try {',
    "    const fs = require('fs')",
    "    for (const path of ['/proc/sys/kernel/osrelease', '/proc/version']) {",
    '      try {',
    "        const contents = String(fs.readFileSync(path, 'utf8'))",
    '        if (/microsoft|wsl/i.test(contents)) return true',
    '      } catch {',
    '      }',
    '    }',
    '  } catch {',
    '    return false',
    '  }',
    '  return false',
    '}',
    '',
    'function resolveWindowsCurlPath(): string | null {',
    '  if (cachedWindowsCurlPath !== undefined) return cachedWindowsCurlPath',
    '  try {',
    "    const fs = require('fs')",
    "    const curlPath = '/mnt/c/Windows/System32/curl.exe'",
    '    cachedWindowsCurlPath = fs.existsSync(curlPath) ? curlPath : null',
    '  } catch {',
    '    cachedWindowsCurlPath = null',
    '  }',
    '  return cachedWindowsCurlPath',
    '}',
    '',
    '// Guest loopback may not reach Windows Orca; retry through host curl.exe.',
    'let lastDeliveredWindowsCurl = null',
    '',
    'async function postViaWindowsCurl(body: string, ompRuntime: boolean, coords): Promise<void> {',
    '  const curlPath = resolveWindowsCurlPath()',
    '  const candidates = []',
    '  const addCandidate = (port, token) => {',
    '    if (!port || !token) return',
    '    if (candidates.some((candidate) => candidate.port === port && candidate.token === token)) return',
    '    candidates.push({ port, token })',
    '  }',
    // Why: whatever landed last is tried first, so an Orca restart costs one refused connect rather
    // than one on every post. Then PTY env — the Orca that launched this pane, since a guest endpoint
    // file can be stale — and last the file, which is the only place a restarted host's token lives.
    '  addCandidate(lastDeliveredWindowsCurl?.port, lastDeliveredWindowsCurl?.token)',
    '  addCandidate(process.env.ORCA_AGENT_HOOK_PORT, process.env.ORCA_AGENT_HOOK_TOKEN)',
    '  addCandidate(coords?.port, coords?.token)',
    "  if (!curlPath || candidates.length === 0) throw new Error('Orca WSL hook bridge unavailable')",
    '  let failure = null',
    '  for (const candidate of candidates) {',
    '    try {',
    '      await postViaWindowsCurlOnce(curlPath, body, ompRuntime, candidate.port, candidate.token)',
    '      lastDeliveredWindowsCurl = candidate',
    '      return',
    '    } catch (error) {',
    '      failure = error',
    '    }',
    '  }',
    '  throw failure',
    '}',
    '',
    'async function postViaWindowsCurlOnce(',
    '  curlPath: string,',
    '  body: string,',
    '  ompRuntime: boolean,',
    '  windowsPort: string,',
    '  windowsToken: string',
    '): Promise<void> {',
    '  const windowsUrl = `http://127.0.0.1:${windowsPort}${resolveHookPath(ompRuntime)}`',
    '  await new Promise<void>((resolve, reject) => {',
    "    const { spawn } = require('child_process')",
    '    const child = spawn(',
    '      curlPath,',
    '      [',
    "        '-sS', '--fail',",
    '        // WSL interop needs a bounded, acknowledged delivery window.',
    "        '--connect-timeout', '3',",
    "        '--max-time', '10',",
    "        '--noproxy', '127.0.0.1',",
    "        '-o', 'NUL',",
    "        '-X', 'POST',",
    "        '-H', 'Content-Type: application/json',",
    "        '-H', `X-Orca-Agent-Hook-Token: ${windowsToken}`,",
    "        '--data-binary', '@-',",
    '        windowsUrl',
    '      ],',
    "      { stdio: ['pipe', 'ignore', 'ignore'] }",
    '    )',
    '    const timer = setTimeout(() => {',
    '      try { child.kill() } catch {}',
    "      reject(new Error('Orca WSL hook delivery timed out'))",
    '    }, 11000)',
    "    if (typeof timer.unref === 'function') timer.unref()",
    '    const fail = (error: Error): void => { clearTimeout(timer); reject(error) }',
    "    child.on('error', fail)",
    "    child.stdin.on('error', fail)",
    "    child.on('close', (code: number | null) => {",
    '      clearTimeout(timer)',
    "      if (code === 0) resolve(); else reject(new Error('Orca WSL hook exit ' + code))",
    '    })',
    '    child.stdin.end(body)',
    '  })',
    '}',
    ''
  ]
}
